import express from "express";

// Создаём Express-приложение
const app = express();

// Порт, на котором будет работать сервер
const PORT = 3000;


// ----------------------------------------------------
// Временные данные
// ----------------------------------------------------

// Пока базы данных нет,
// поэтому товары просто храним в массиве.
const products = [
    {
        id: 1,
        name: "Laptop",
        price: 350000
    },
    {
        id: 2,
        name: "Mouse",
        price: 8000
    }
];


// ----------------------------------------------------
// 1. Простой GET-маршрут
// ----------------------------------------------------

// Общая структура маршрута:
//
// app.METHOD(PATH, HANDLER);
//
// app      — Express-приложение
// get      — HTTP-метод
// "/"      — путь
// функция  — обработчик запроса

app.get("/", (req, res) => {

    // res.send() отправляет ответ клиенту
    res.send("Express server is running");

});


// ----------------------------------------------------
// 2. GET /api/products
// Получение списка товаров
// ----------------------------------------------------

// Если клиент отправит:
//
// GET http://localhost:3000/api/products
//
// Express найдёт этот маршрут
// по двум признакам:
//
// 1. HTTP-метод GET
// 2. путь /api/products

app.get("/api/products", (req, res) => {

    // res.json() отправляет данные
    // клиенту в формате JSON

    res.json(products);

});


// ----------------------------------------------------
// 3. POST /api/products
// Создание товара
// ----------------------------------------------------

// URL тот же:
//
// /api/products
//
// но HTTP-метод уже другой.
//
// Поэтому для Express это другой endpoint.

app.post("/api/products", (req, res) => {

    // В этой лекции тело запроса ещё не разбираем.
    // Поэтому просто показываем,
    // что был вызван обработчик POST.

    res.status(201).json({
        message: "Product created"
    });

});


// ----------------------------------------------------
// 4. PUT /api/products
// Полная замена данных
// ----------------------------------------------------

// PUT обычно используют,
// когда ресурс нужно заменить полностью.

app.put("/api/products", (req, res) => {

    res.status(200).json({
        message: "Products completely replaced"
    });

});


// ----------------------------------------------------
// 5. PATCH /api/products
// Частичное изменение данных
// ----------------------------------------------------

// PATCH используют,
// когда нужно изменить только часть данных ресурса.

app.patch("/api/products", (req, res) => {

    res.status(200).json({
        message: "Products partially updated"
    });

});


// ----------------------------------------------------
// 6. DELETE /api/products
// Удаление ресурса
// ----------------------------------------------------

app.delete("/api/products", (req, res) => {

    res.status(200).json({
        message: "Products deleted"
    });

});


// ----------------------------------------------------
// 7. Другой ресурс: категории
// ----------------------------------------------------

// Теперь путь другой:
//
// /api/categories

app.get("/api/categories", (req, res) => {

    res.json([
        "Computers",
        "Accessories",
        "Storage"
    ]);

});


// ----------------------------------------------------
// 8. Создание категории
// ----------------------------------------------------

app.post("/api/categories", (req, res) => {

    res.status(201).json({
        message: "Category created"
    });

});


// ----------------------------------------------------
// 9. Заказы
// ----------------------------------------------------

app.get("/api/orders", (req, res) => {

    res.json([
        {
            id: 1,
            status: "new"
        },
        {
            id: 2,
            status: "completed"
        }
    ]);

});


app.post("/api/orders", (req, res) => {

    res.status(201).json({
        message: "Order created"
    });

});


// ----------------------------------------------------
// 10. Корзина
// ----------------------------------------------------

app.get("/api/cart", (req, res) => {

    res.json([
        {
            product: "Laptop",
            quantity: 1
        }
    ]);

});


// Очистка корзины

app.delete("/api/cart", (req, res) => {

    res.status(200).json({
        message: "Cart cleared"
    });

});


// ----------------------------------------------------
// Запуск HTTP-сервера
// ----------------------------------------------------

app.listen(PORT, () => {

    console.log(
        `Server started: http://localhost:${PORT}`
    );

});